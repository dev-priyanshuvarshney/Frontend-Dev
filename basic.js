let a = Math.floor(Math.random() * 100);

console.log("Marks: ", a);
if (a > 90) {
    console.log("O")
} else if (a > 80) {
    console.log("A+");
} else if (a > 70) {
    console.log("A");
} else if (a > 60) {
    console.log("B+");
} else if (a > 50) {
    console.log("B");
} else if (a > 40) {
    console.log("C");
}